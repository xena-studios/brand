// Every brand's colours in the W3C Design Tokens format (DTCG 2025.10), beside the CSS and
// JSON: tokens/<brand>.tokens.json. It's the standard exchange format, so Style Dictionary
// (to make Tailwind, Swift, Android or any other format), Tokens Studio and Figma can read
// the brand's colours straight from here. Made from the tokens/<brand>.json files the build
// writes, so the two always agree.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");

const NAMES: Record<string, string> = {
  colors: "Xena Studios", raptor: "Raptor", neoskript: "NeoSkript", mostwanted: "MostWanted", airfields: "Airfields", plugins: "The plugin family",
};

/** A colour token: sRGB components, and the hex for tools that want it. */
export function colorToken(hex: string, extra: Record<string, unknown> = {}) {
  const components = [1, 3, 5].map((i) => +(parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(4));
  return { $type: "color", $value: { colorSpace: "srgb", components, hex: hex.toUpperCase() }, ...extra };
}

/** tokens/<name>.tokens.json from tokens/<name>.json. Raptor's oklch originals ride along as an extension. */
export function dtcg(name: string) {
  const flat: Record<string, string | { oklch: string | null; hex: string }> = JSON.parse(fs.readFileSync(path.join(ROOT, `tokens/${name}.json`), "utf8"));
  const group: Record<string, unknown> = { $description: `${NAMES[name] ?? name}'s colours. Generated by the brand build from tokens/${name}.json: don't edit by hand.` };
  for (const [key, v] of Object.entries(flat)) {
    group[key] = typeof v === "string" ? colorToken(v) : colorToken(v.hex, v.oklch ? { $extensions: { "co.xenastudios.oklch": v.oklch } } : {});
  }
  return { [name === "colors" ? "xena" : name]: group };
}

export function writeDtcg() {
  for (const name of Object.keys(NAMES)) {
    if (!fs.existsSync(path.join(ROOT, `tokens/${name}.json`))) continue;
    fs.writeFileSync(path.join(ROOT, `tokens/${name}.tokens.json`), JSON.stringify(dtcg(name), null, 2) + "\n");
  }
}
